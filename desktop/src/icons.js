export function icon(name, size = 20) {
  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("width", size);
  svg.setAttribute("height", size);
  svg.setAttribute("fill", "none");
  svg.setAttribute("stroke", "currentColor");
  svg.setAttribute("stroke-width", "1.9");
  svg.setAttribute("stroke-linecap", "round");
  svg.setAttribute("stroke-linejoin", "round");
  svg.classList.add("ico");
  svg.innerHTML = ICONS[name] || "";
  return svg;
}

export function iconButton(name, { size = 18, title = "", cls = "" } = {}) {
  const b = document.createElement("button");
  b.className = ("icon-btn " + cls).trim();
  if (title) { b.title = title; b.setAttribute("aria-label", title); }
  b.append(icon(name, size));
  return b;
}

// Substitui <span data-icon="home"> por SVG. Chamar após render.
export function hydrateIcons(root = document) {
  root.querySelectorAll("[data-icon]").forEach((node) => {
    if (node.__iconDone === node.dataset.icon) return;
    const size = node.dataset.iconSize ? +node.dataset.iconSize : 20;
    node.replaceChildren(icon(node.dataset.icon, size));
    node.__iconDone = node.dataset.icon;
  });
}
